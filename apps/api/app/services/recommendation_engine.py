def _recommendation_for_action(action: str) -> Optional[RecommendationType]:
    mapping = {
        "restart_service": RecommendationType.CONSIDER_RESTART,
        "restart_instance": RecommendationType.CONSIDER_RESTART,
        "rollback_deployment": RecommendationType.CONSIDER_ROLLBACK,
        "rollback_configuration": RecommendationType.CONSIDER_ROLLBACK,
        "route_traffic_to_healthy_instance": RecommendationType.CONSIDER_TRAFFIC_SHIFT,
        "scale_service_within_limit": RecommendationType.REVIEW_CAPACITY,
    }
    return mapping.get(action.lower())


def _action_tallies(
    retrieval: RetrievalResult,
) -> tuple[dict[str, int], dict[str, int]]:
    """Counts per action across comparable episodes, and their successes."""
    counts: dict[str, int] = {}
    successes: dict[str, int] = {}
    for match in retrieval.matches:
        resolution = match.resolution or {}
        for action in resolution.get("action_types") or []:
            counts[action] = counts.get(action, 0) + 1
            if _match_succeeded(match):
                successes[action] = successes.get(action, 0) + 1
    return counts, successes


def _match_succeeded(match: Any) -> bool:
    resolution = match.resolution or {}
    if resolution.get("rollback_performed"):
        return False
    if resolution.get("outcome") == "effective":
        return True
    if match.outcome in ("effective", "patch_verified"):
        return True
    return False


def _confidence_for(
    sample: int, successes: int, settings: Settings
) -> KnowledgeConfidence:
    """Bucket the historical evidence behind one recommendation (§34)."""
    if sample < settings.INTELLIGENCE_MIN_SAMPLES_CANDIDATE:
        return KnowledgeConfidence.UNKNOWN
    ratio = successes / sample if sample else 0.0
    if sample >= settings.INTELLIGENCE_MIN_SAMPLES_HIGH_CONFIDENCE and ratio >= 0.8:
        return KnowledgeConfidence.HIGH
    if sample >= settings.INTELLIGENCE_MIN_SAMPLES_VALIDATION and ratio >= 0.6:
        return KnowledgeConfidence.MEDIUM
    return KnowledgeConfidence.LOW


def _confidence_score(confidence: KnowledgeConfidence) -> float:
    return {
        KnowledgeConfidence.UNKNOWN: 0.0,
        KnowledgeConfidence.LOW: 0.33,
        KnowledgeConfidence.MEDIUM: 0.66,
        KnowledgeConfidence.HIGH: 1.0,
    }.get(confidence, 0.0)


