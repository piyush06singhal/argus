"""ARGUS Reliability Recommendation Engine (Phase 10 §38–§43, §81).

Produces advisory recommendations from current evidence, validated knowledge and
historical outcomes. The rules that shape it:

* **A recommendation cites its sources or it is not created.** ``knowledge_ids``
  and ``experience_ids`` are populated from rows that exist, and
  ``current_evidence`` names the incident, component and observed signals. No
  recommendation is written with an empty evidence record.
* **It never executes.** The strongest thing a recommendation carries is
  :func:`policy_note_for`: what Phase 9 *would* demand if a human chose to act.
  §42 asks for that note explicitly, and it is generated by reading the same
  policy and registry the executor would use — not by restating a guess.
* **Uncertainty travels with the claim** (§40). ``limitations`` always includes
  the sample size behind any historical claim, and the ranking criteria are
  stored in ``ranking`` rather than left implicit.
* **Being wrong is learnable** (§43). ``decide`` and ``record_outcome`` are
  separate: "the engineer accepted it" and "it worked" are different facts, and
  the second is what the learning loop feeds on.
"""

